import type { World } from '../sim/world';

/** 世界 → 可传输快照（P2P 房主用）。events 是这一拍攒下来的特效事件，客人靠它播特效 */
export function serializeWorld(w: World, events: unknown[] = []): unknown {
  return {
    time: w.time,
    state: w.state,
    wave: { n: w.wave.n, phase: w.wave.phase, timer: w.wave.timer, remaining: w.remainingEnemies() },
    players: w.players.map((p, i) => ({
      id: i + 1,
      x: p.pos.x,
      y: p.pos.y,
      aim: p.aim,
      hp: p.hp,
      maxHp: p.maxHp,
      stamina: p.stamina,
      weaponId: p.weaponId,
      shieldHp: p.shieldHp,
      shieldAngle: p.shieldAngle,
      meteorT: p.meteorT,
      stoneT: p.stoneT,
      eggT: p.eggT,
      leapT: p.leapT,
      leapHangT: p.leapHangT,
      landT: p.landT,
      rollT: p.rollT,
      reloading: p.reloading,
      ammo: p.ammo,
      charge: p.charge,
      alive: p.alive,
      coins: p.coins,
      skillCd: p.skillCd.slice(),
      mode: p.mode,
      throwTarget: p.throwTarget ? { x: p.throwTarget.x, y: p.throwTarget.y } : null,
      aiming: p.aiming,
      leapTo: { x: p.leapTo.x, y: p.leapTo.y },
    })),
    enemies: w.enemies.map((e) => ({
      id: e.id,
      kind: e.kind,
      x: e.pos.x,
      y: e.pos.y,
      hp: e.hp,
      maxHp: e.maxHp,
      facing: e.facing,
      windup: e.windup,
      windupTotal: e.windupTotal,
      windupAngle: e.windupAngle,
      hitFlash: e.hitFlash,
      attackAnim: e.attackAnim,
      rootT: e.rootT,
      slowT: e.slowT,
    })),
    lasers: w.lasers.map((l) => ({ x: l.pos.x, y: l.pos.y, angle: l.angle, radius: l.radius, orb: l.orb, lift: l.lift })),
    zones: w.zones.map((z) => ({ x: z.pos.x, y: z.pos.y, radius: z.radius, ttl: z.ttl, maxTtl: z.maxTtl, poison: !!z.poison })),
    shots: w.shots.map((s) => ({ x: s.pos.x, y: s.pos.y, radius: s.radius })),
    bottles: w.bottles.map((b) => ({ x: b.pos.x, y: b.pos.y })),
    crystals: w.crystals.map((c) => ({ x: c.pos.x, y: c.pos.y, kind: c.kind, hp: c.hp, maxHp: c.maxHp, alive: c.alive })),
    events,
  };
}
